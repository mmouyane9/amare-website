/**
 * Page Discovery Service
 *
 * Auto-discovers every public website page from the project HTML files.
 * Reusable – call `getWebsitePages()` anywhere to get the full page list.
 *
 * Ignored pages:
 *   - Dashboard / Admin pages
 *   - Login
 *   - Members
 *   - News dashboard
 *   - Updates dashboard
 *   - Store dashboard
 *   - Control Panel
 *   - Content Editor
 *   - Preview utility
 *
 * When a new HTML page is added to the website, add it to the manifest below
 * and it immediately appears in the Content Editor sidebar.
 */

export interface DiscoveredPage {
  /** Unique identifier (derived from filename) */
  id: string
  /** Display name extracted from the HTML <title> tag */
  name: string
  /** Public URL path relative to the site root */
  path: string
  /** Navigation section the page belongs to */
  section: string
  /** Sort order matching the website navigation */
  order: number
}

/**
 * Auto-assigns a Lucide icon name to each page based on its path/section.
 * Icons are determined programmatically, not hardcoded per page.
 */
function assignIcon(page: DiscoveredPage): string {
  const path = page.path.toLowerCase()
  const name = page.name.toLowerCase()
  const section = page.section.toLowerCase()

  if (page.id === 'home') return 'home'
  if (section.includes('نبذة') || section.includes('about') || page.id === 'central-office')
    return 'building2'
  if (name.includes('رؤي') || name.includes('vision')) return 'eye'
  if (name.includes('رسال') || name.includes('mission')) return 'target'
  if (name.includes('قيم') || name.includes('values')) return 'heart'
  if (name.includes('خرائط') || name.includes('توسع') || name.includes('expansion'))
    return 'map'
  if (section.includes('فرع') || section.includes('branch') || path.includes('regional-branches'))
    return 'map-pinned'
  if (
    name.includes('انخراط') ||
    name.includes('join') ||
    name.includes('register') ||
    name.includes('تسجيل')
  )
    return 'user-plus'
  if (name.includes('تجديد') || name.includes('renewal')) return 'refresh-cw'
  if (name.includes('وثائ') || name.includes('document')) return 'files'
  if (name.includes('قانون') || name.includes('bylaw') || name.includes('regulation'))
    return 'book-open'
  if (name.includes('ميثاق') || name.includes('charter')) return 'scroll'
  if (name.includes('إيداع') || name.includes('deposit')) return 'folder-open'
  if (name.includes('إشعار') || name.includes('notification') || name.includes('خرجات'))
    return 'bell'
  if (name.includes('استمار') || name.includes('application')) return 'clipboard-list'
  if (name.includes('التزا') || name.includes('commitment')) return 'file-check'
  if (name.includes('اتصل') || name.includes('contact') || name.includes('تواصل')) return 'mail'
  return 'file-text'
}

