export interface ResolvedPage extends DiscoveredPage {
  icon: string
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/** Returns all discovered website pages, ordered by navigation position. */
export function getWebsitePages(): ResolvedPage[] {
  return [...MANIFEST]
    .sort((a, b) => a.order - b.order)
    .map((page) => ({ ...page, icon: assignIcon(page) }))
}

/** Finds a single page by its id. */
export function getPageById(id: string): ResolvedPage | undefined {
  return getWebsitePages().find((page) => page.id === id)
}

/** Finds pages whose path matches a given search term. */
export function searchPages(query: string): ResolvedPage[] {
  const trimmed = query.trim().toLowerCase()
  if (!trimmed) return getWebsitePages()
  return getWebsitePages().filter(
    (page) =>
      page.name.toLowerCase().includes(trimmed) ||
      page.section.toLowerCase().includes(trimmed) ||
      page.path.toLowerCase().includes(trimmed),
  )
}

/** Returns unique section names in navigation order. */
export function getSections(): string[] {
  const pages = getWebsitePages()
  const seen: Record<string, boolean> = {}
  const result: string[] = []
  for (const page of pages) {
    if (!seen[page.section]) {
      seen[page.section] = true
      result.push(page.section)
    }
  }
  return result
}
